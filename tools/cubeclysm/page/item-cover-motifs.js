export function paintCoverMotif(ctx, motif, colors, key) {
  const pixels = art[motif];
  if (!pixels) return false;
  const [background, light, accent, middle] = colors;
  const inks = { '+': accent, 'o': light, '#': middle };
  ctx.fillStyle = background;
  ctx.fillRect(0, 0, 64, 40);
  const flipped = (key & 2) !== 0;
  for (const [y, row] of pixels.entries()) {
    for (const [x, pixel] of [...row].entries()) {
      if (pixel === '.') continue;
      ctx.fillStyle = inks[pixel];
      ctx.fillRect((flipped ? 15 - x : x) * 4, y * 4, 4, 4);
    }
  }
  return true;
}

